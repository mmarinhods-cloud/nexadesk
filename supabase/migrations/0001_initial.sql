create function public.create_organization(workspace_name text) returns uuid
language plpgsql security definer set search_path = '' as $$
declare result uuid; clean_name text; user_id uuid;
begin
  user_id := auth.uid();
  if user_id is null then raise exception 'Authentication required'; end if;
  clean_name := trim(workspace_name);
  if length(clean_name) < 2 or length(clean_name) > 80 then raise exception 'Invalid workspace name'; end if;
  insert into public.organizations(name, slug) values (clean_name, lower(regexp_replace(clean_name, '[^a-zA-Z0-9]+', '-', 'g')) || '-' || substr(gen_random_uuid()::text, 1, 8)) returning id into result;
  insert into public.organization_members(organization_id, user_id, role) values (result, user_id, 'owner');
  return result;
end; $$;
revoke all on function public.create_organization(text) from public;
grant execute on function public.create_organization(text) to authenticated;

create function public.guard_member_roles() returns trigger
language plpgsql security definer set search_path = '' as $$
declare org uuid; owner_count integer;
begin
  org := case when tg_op = 'DELETE' then old.organization_id else new.organization_id end;
  if tg_op = 'INSERT' then
    if new.role in ('owner', 'admin') and public.is_member(org) and not public.has_role(org, array['owner']::public.member_role[]) then
      raise exception 'Only an owner can grant elevated roles';
    end if;
    return new;
  end if;
  if tg_op = 'UPDATE' and (new.organization_id <> old.organization_id or new.user_id <> old.user_id) then
    raise exception 'Membership identity cannot be changed';
  end if;
  if old.role = 'owner' then
    select count(*) into owner_count from public.organization_members where organization_id = org and role = 'owner';
    if owner_count <= 1 and (tg_op = 'DELETE' or new.role <> 'owner') then
      raise exception 'An organization must retain an owner';
    end if;
  end if;
  if tg_op = 'UPDATE' and (new.role in ('owner', 'admin') or old.role in ('owner', 'admin')) and not public.has_role(org, array['owner']::public.member_role[]) then
    raise exception 'Only an owner can change elevated roles';
  end if;
  if tg_op = 'DELETE' and old.role in ('owner', 'admin') and not public.has_role(org, array['owner']::public.member_role[]) then
    raise exception 'Only an owner can remove elevated roles';
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end; $$;
create trigger member_role_guard before insert or update or delete on public.organization_members
for each row execute function public.guard_member_roles();

